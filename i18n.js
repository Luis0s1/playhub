function detectAutoLanguage() {
    const saved = localStorage.getItem('playhub_lang');
    if (saved && saved !== 'auto') return saved;

    const langs = navigator.languages || [navigator.language || 'en'];
    for (let l of langs) {
        const code = l.toLowerCase();
        if (code === 'pt-br' || (code.startsWith('pt') && (Intl.DateTimeFormat().resolvedOptions().timeZone || '').includes('America/Sao_Paulo'))) {
            return 'pt-BR';
        }
        if (code.startsWith('pt')) return 'pt-PT';
        if (code.startsWith('en')) return 'en';
        if (code.startsWith('es')) return 'es';
        if (code.startsWith('fr')) return 'fr';
        if (code.startsWith('ru')) return 'ru';
        if (code.startsWith('de')) return 'de';
        if (code.startsWith('it')) return 'it';
        if (code.startsWith('ja')) return 'ja';
        if (code.startsWith('ko')) return 'ko';
        if (code.startsWith('zh')) return 'zh-CN';
        if (code.startsWith('ar')) return 'ar';
        if (code.startsWith('hi')) return 'hi';
        if (code.startsWith('tr')) return 'tr';
        if (code.startsWith('pl')) return 'pl';
        if (code.startsWith('nl')) return 'nl';
        if (code.startsWith('id')) return 'id';
        if (code.startsWith('uk')) return 'uk';
    }
    return 'en';
}

let activeLangKey = detectAutoLanguage();

function t(key) {
    const dict = I18N_DICT[activeLangKey] || I18N_DICT['en'];
    return dict[key] || I18N_DICT['en'][key] || key;
}

function applyTranslations() {
    document.documentElement.lang = activeLangKey;
    document.documentElement.dir = (activeLangKey === 'ar') ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const k = el.getAttribute('data-i18n');
        el.textContent = t(k);
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const k = el.getAttribute('data-i18n-ph');
        el.placeholder = t(k);
    });
}
